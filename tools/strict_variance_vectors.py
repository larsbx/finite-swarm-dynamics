"""Render fixed rational vectors as kernel-checked Lean examples.

This renderer only quotes input and expected output; it does not calculate
variance or decide a vector's mathematical classification.
"""
from fractions import Fraction
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VECTORS = ROOT / "conformance/strict_variance_Q_v1.json"
TARGET = ROOT / "formal/general/ChromoswarmStrictVectors.lean"


def rat(text):
    q = Fraction(text)
    return f"({q.numerator} / {q.denominator} : ℚ)"


def vector(xs):
    return "![" + ", ".join(xs) + "]"


def render():
    data = json.loads(VECTORS.read_text())
    assert data["schema"] == "strict_variance_Q_v1"
    parts = ["""import ChromoswarmStrict

/-! Generated by `python -m tools.strict_variance_vectors` from fixed exact
regression vectors. Checked with ordinary Lean tactics, without native evaluation.
The independent Python tests recompute the same quantities using Fraction. -/
namespace ChromoswarmStrictVectors
open ChromoswarmJensen ChromoswarmPlanar ChromoswarmStrict
set_option maxRecDepth 4096
set_option maxHeartbeats 800000
"""]
    for c in data["cases"]:
        name = c["id"]
        assert name.replace("_", "").isalnum()
        n = len(c["matrix"])
        matrix = vector([vector([rat(x) for x in row]) for row in c["matrix"]])
        state = vector(["(" + ", ".join(rat(x) for x in row) + ")" for row in c["velocities"]])
        parts.append(f"""
-- {c['kind']}
def {name}_P : Fin {n} → Fin {n} → ℚ := {matrix}
def {name}_v : Fin {n} → ℚ × ℚ := {state}

theorem {name}_values :
    blueVariance Finset.univ {name}_v = {rat(c['old_variance'])} ∧
    blueVariance Finset.univ (applyVec Finset.univ {name}_P {name}_v) = {rat(c['new_variance'])} ∧
    pairLoss Finset.univ {name}_P {name}_v = {rat(c['pair_loss'])} := by
  norm_num [{name}_P, {name}_v, blueVariance, variance, applyVec,
    apply, pairLoss, lossTerm, blueDistance, Fin.sum_univ_succ, Matrix.cons_val_two, Matrix.cons_val_three, Matrix.vecHead, Matrix.vecTail]
""")
        flags = [
            ("row_unital", f"∀ i, (∑ j, {name}_P i j) = 1"),
            ("column_unital", f"∀ j, (∑ i, {name}_P i j) = 1"),
            ("nonnegative", f"∀ i j, 0 ≤ {name}_P i j"),
            ("mixes_distinct", f"mixesDistinct Finset.univ {name}_P {name}_v"),
        ]
        for key, prop in flags:
            if not c[key]:
                prop = f"¬ ({prop})"
            tactic = f"norm_num [mixesDistinct, {name}_P, {name}_v, Fin.forall_fin_succ, Fin.exists_fin_succ, Fin.sum_univ_succ, Matrix.cons_val_two, Matrix.cons_val_three, Matrix.vecHead, Matrix.vecTail]"
            parts.append(f"theorem {name}_{key} : {prop} := by {tactic}\n")
    parts.append("\nend ChromoswarmStrictVectors\n")
    return "".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit("Lean vectors are stale; run python -m tools.strict_variance_vectors")
    else:
        TARGET.write_text(expected)
